using ChronoTravelers.Core.Events;

namespace ChronoTravelers.Core.Tests.Events;

public class GameEventTests
{
    [Fact]
    public void Slain_FormatsVictimAndKiller()
    {
        var evt = GameEvent.Slain("Rook", "Feral Dog");
        Assert.Equal("Rook was slain by Feral Dog.", evt.Message);
    }

    [Fact]
    public void LevelReached_FormatsNameAndLevel()
    {
        var evt = GameEvent.LevelReached("Rook", 5);
        Assert.Equal("Rook reached level 5!", evt.Message);
    }

    [Fact]
    public void Events_CarryAnOptionalYear_ForTheInlineFeedFilter()
    {
        Assert.Null(GameEvent.Slain("A", "B").Year);
        Assert.Equal(3200, GameEvent.Slain("A", "B", 3200).Year);
        Assert.Equal(4000, GameEvent.Ambushed("Beast", "Rook", 7, 4000).Year);
        Assert.Equal(2500, GameEvent.LevelReached("Rook", 9, 2500).Year);
        Assert.Equal(3400, GameEvent.TimeTraveled("Rook", 3400).Year);
    }

    [Fact]
    public void Slain_GivesCreaturesAnArticle_CapitalisedFirst_LowercaseAfter()
    {
        Assert.Equal("An Ashfall Echo was slain by an Ashfall Echo.",
            GameEvent.Slain("Ashfall Echo", "Ashfall Echo", victimIsCreature: true, killerIsCreature: true).Message);

        Assert.Equal("A Rubble Hulk was slain by a Dune Stalker.",
            GameEvent.Slain("Rubble Hulk", "Dune Stalker", victimIsCreature: true, killerIsCreature: true).Message);
    }

    [Fact]
    public void Slain_LeavesNamedAgentsBare_AndMixesWithCreaturesCorrectly()
    {
        Assert.Equal("Fang was slain by an Ashfall Echo.",
            GameEvent.Slain("Fang", "Ashfall Echo", killerIsCreature: true).Message);

        Assert.Equal("A Scavenger was slain by Fang.",
            GameEvent.Slain("Scavenger", "Fang", victimIsCreature: true).Message);
    }

    [Fact]
    public void Feed_DropsTheAutoGeneratedNpcInstanceSuffix()
    {
        Assert.Equal("A Scavenger was slain by Static.",
            GameEvent.Slain("Scavenger", "Static 2", victimIsCreature: true).Message);
        Assert.Equal("Gristle reached level 12!", GameEvent.LevelReached("Gristle 3", 12).Message);
        Assert.Equal("Fang time traveled to 3200 A.D.", GameEvent.TimeTraveled("Fang 2", 3200).Message);
        Assert.Equal("An Ashfall Echo ambushes Rook for 7.", GameEvent.Ambushed("Ashfall Echo", "Rook", 7).Message);
    }

    [Fact]
    public void Slain_DoesNotDoubleUpAnExistingDeterminer()
    {
        // The Warden's name already carries "The".
        Assert.Equal("The Warden of 3200 was slain by Rook.",
            GameEvent.Slain("The Warden of 3200", "Rook", victimIsCreature: true).Message);
    }
}
